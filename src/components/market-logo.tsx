export function MarketplaceToggle({
  marketplace,
  selected,
  onClick,
  count,
  className,
}: {
  marketplace: Market;
  selected: boolean;
  onClick: () => void;
  count?: number;
  className?: string;
}) {
  return (
    <button
      type="button"
      onClick={onClick}
      aria-pressed={selected}
      aria-label={count != null ? `${LABEL[marketplace]} ${count}` : LABEL[marketplace]}
      className={cn(
        "inline-flex h-11 items-center gap-2 rounded-full border px-3 transition-[border-color,background-color,box-shadow] duration-150",
        selected
          ? "border-accent bg-surface shadow-[var(--shadow-border)]"
          : "border-border bg-transparent opacity-70 hover:opacity-100",
        className,
      )}
    >
      <MarketplaceLogo marketplace={marketplace} />
      {count != null && <span className="text-xs tabular-nums text-muted">{count}</span>}
    </button>
  );
}
